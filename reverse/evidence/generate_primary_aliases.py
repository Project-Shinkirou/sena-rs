"""Generate aliases only where primary/extcall slots share the SAME PE dword.

This avoids the old name catalog's unbounded table-walk aliases. The upper
boundary is the audited primary range, not a claim about arbitrary releases.
"""
import json
import hashlib
import struct
from pathlib import Path
from audit_native_interfaces import PE

pe = PE('reverse/Game.exe')
base = 0x4BB1D0
regions = [(35,40,23),(40,80,10),(80,96,5),(96,108,6),(108,171,9),
           (171,176,12),(176,224,2),(224,252,13),(252,263,7)]
lines = ['//! Generated by reverse/evidence/generate_primary_aliases.py.',
         '//! Aliases share native dispatch-table storage; this is not handler parity.',
         'pub(super) fn primary_extcall(opcode: u16) -> Option<(u16, u16)> {',
         '    match opcode {']
rows = []
for start,end,category in regions:
    category_base, = struct.unpack_from('<I',pe.data,pe.offset(0x49C360+category*4-pe.base))
    assert category_base == base+start*4
    for opcode in range(start,end):
        handler, = struct.unpack_from('<I',pe.data,pe.offset(base+opcode*4-pe.base))
        if not handler:
            continue
        index = opcode-start
        rows.append({'opcode':opcode,'category':category,'index':index,'handler':hex(handler)})
        lines.append(f'        {opcode} => Some(({category}, {index})),')
lines += ['        _ => None,', '    }','}','']
Path('crates/pal-vm/src/runtime/primary_aliases.rs').write_text('\n'.join(lines))
Path('reverse/evidence/primary-extcall-aliases.json').write_text(json.dumps(rows,indent=2)+'\n')
coverage_path = Path('reverse/evidence/primary-opcode-coverage.json')
coverage = json.loads(coverage_path.read_text())
aliases = {row['opcode']: row for row in rows}
for row in coverage['rows']:
    row.setdefault('pre_fix_rust_status', row['rust_status'])
    if row['opcode'] in aliases:
        alias = aliases[row['opcode']]
        assert int(row['native_address'], 16) == int(alias['handler'], 16)
        row['extcall'] = [alias['category'], alias['index']]
        row['rust_status'] = ('shared_wait_with_native_operand_count'
                              if row['opcode'] in (252, 253)
                              else 'shared_extcall_dispatch_route')
coverage['implementation_note'] = (
    'All 248 nonzero slots have dispatch routes; this does not certify handler '
    'semantics. See reverse/fx-vm-implementation.md. Baseline statuses are retained.')
coverage['rust_source_sha256'] = hashlib.sha256(
    Path('crates/pal-vm/src/runtime.rs').read_bytes()).hexdigest()
coverage_path.write_text(json.dumps(coverage, indent=2)+'\n')
print(f'{len(rows)} aliases derived from shared dispatch storage')
