"""Generate the newer build's reviewed VM signatures and primary aliases."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EVIDENCE = ROOT / "reverse/evidence"

def outputs():
    aliases = json.loads((EVIDENCE / "totsulover-primary-aliases.json").read_text())
    contracts = json.loads((EVIDENCE / "totsulover-reviewed-extcalls.json").read_text())
    followup = json.loads((EVIDENCE / "totsulover-followup-reviewed.json").read_text())
    reviewed = {(row["category"], row["index"]): row for row in contracts["reviewed"]}
    for row in followup["contracts"]:
        if "stack_pop_order" not in row:
            assert (row["category"], row["index"]) == (18, 90)
            row["stack_pop_order"] = ["format", "value0", "value1", "value2", "value3", "value4", "value5", "value6"]
        reviewed[(row["category"], row["index"])] = row
    audio = json.loads((EVIDENCE / "totsulover-audio-image-reviewed.json").read_text())
    for row in audio["rows"]:
        row["writes_destination"] = row["destination_write"] != "never"
        reviewed[(row["category"], row["index"])] = row
    movie = json.loads((ROOT / "reverse/contracts/audio_video.json").read_text())
    for row in movie["vm_wrappers"]:
        if row["build"] != "totsulover":
            continue
        reviewed[(row["category"], row["index"])] = {
            **row, "argc": row["arity"], "stack_pop_order": row["arguments_pop_order"],
            "writes_destination": row.get("writes_destination", row["category"] == 11 and row["index"] in (1, 10, 12, 13)),
            "evidence": row["evidence"][0],
        }
    buttons = json.loads((ROOT / "reverse/contracts/input_buttons.json").read_text())
    for row in buttons["vm_wrappers"]:
        if row["build"] != "totsulover":
            continue
        reviewed[(row["category"], row["index"])] = {
            **row, "argc": row["arity"], "stack_pop_order": row["arguments_pop_order"],
            "writes_destination": (row["category"], row["index"]) not in {(8, 13), (8, 36), (9, 35)},
            "evidence": row["evidence"][0],
        }
    graphics = json.loads((EVIDENCE / "totsulover-graphics-reviewed.json").read_text())
    for row in graphics["rows"]:
        reviewed[(row["category"], row["index"])] = row
    extensions = json.loads((EVIDENCE / "totsulover-twelve-reviewed.json").read_text())
    for row in extensions["rows"]:
        reviewed[(row["category"], row["index"])] = row
    # Direct destination stores were reviewed in the preserved wrapper bodies.
    preserved = {(2, 47), (3, 59), (8, 36), (9, 44), (12, 0), (12, 1), (18, 91)}
    for coordinate in preserved:
        reviewed[coordinate]["writes_destination"] = False
    lines = ["// Generated by reverse/evidence/generate_registered_dispatch.py.",
             "pub(super) fn registered_primary_extcall(opcode: u16) -> Option<(u16, u16)> {",
             "    match opcode {"]
    for row in aliases["rows"]:
        lines.append(f'        {row["opcode"]} => Some(({row["category"]}, {row["index"]})),')
    lines += ["        _ => None,", "    }", "}", ""]
    signatures = ["// Generated by reverse/evidence/generate_registered_dispatch.py.",
        "/// A reviewed VM wrapper signature, not a native PAL DLL ABI.",
        "#[derive(Clone, Copy, Debug)]",
        "pub struct RegisteredExtSig {",
        "    pub category: u16,", "    pub index: u16,", "    pub name: &'static str,",
        "    pub pop_count: usize,", "    pub writes_destination: Option<bool>,", "    pub parameters: &'static [&'static str],",
        "    pub evidence: &'static str,", "}",
        "pub const REGISTERED_EXTSIGS: &[RegisteredExtSig] = &["]
    for _, row in sorted(reviewed.items()):
        assert row["argc"] == len(row["stack_pop_order"])
        signatures += ["    RegisteredExtSig {",
            f'        category: {row["category"]}, index: {row["index"]},',
            f'        name: {json.dumps(row["name"])}, pop_count: {row["argc"]},',
            '        writes_destination: ' + ('Some(' + str(row["writes_destination"]).lower() + ')' if "writes_destination" in row else 'None') + ',', 
            "        parameters: &[" + ", ".join(json.dumps(x) for x in row["stack_pop_order"]) + "],",
            f'        evidence: {json.dumps(row["evidence"] + " " + row["handler"])},', "    },"]
    signatures += ["];", "",
        "pub fn lookup_registered_sig(category: u16, index: u16) -> Option<&'static RegisteredExtSig> {",
        "    REGISTERED_EXTSIGS.iter().find(|sig| sig.category == category && sig.index == index)", "}", ""]
    return {ROOT / "crates/pal-vm/src/runtime/registered_primary_aliases.rs": "\n".join(lines),
            ROOT / "crates/pal-script/src/extsig_registered.rs": "\n".join(signatures)}

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, source in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != source:
                raise SystemExit(f"Stale registered dispatch declarations: {path}")
        else:
            path.write_text(source)
