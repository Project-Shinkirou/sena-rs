"""Generate native PAL declarations from reviewed ABI contracts.

Run with --check in validation. IDA prototype guesses are never imported here.
The native declarations are exclusively Win32 x86; portable adapters are named
in the manifest and do not reinterpret Rust handles as native addresses.
"""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
RUST_TYPES = {
    "int16_t": "i16",
    "uint16_t": "u16",
    "uint8_t": "u8",
    "int32_t": "i32",
    "uint32_t": "u32",
    "float": "f32",
    "PalWaveFormatEx32 *": "*mut PalWaveFormatEx32",
    "PalSpriteInfoKoikake32 *": "*mut PalSpriteInfoKoikake32",
    "const PalSpriteInfoKoikake32 *": "*const PalSpriteInfoKoikake32",
    "PalSpriteOpaque *": "*mut PalSpriteOpaque",
    "const PalSpriteOpaque *": "*const PalSpriteOpaque",
    "PalRenderOpaque *": "*mut PalRenderOpaque",
    "PalTaskOpaque *": "*mut PalTaskOpaque",
    "const PalAnimationFrame32 *": "*const PalAnimationFrame32",
    "const char *": "*const core::ffi::c_char",
    "char *": "*mut core::ffi::c_char",
    "const PalRect32 *": "*const PalRect32",
    "PalRect32 *": "*mut PalRect32",
    "const void *": "*const core::ffi::c_void",
    "void *": "*mut core::ffi::c_void",
    "int32_t *": "*mut i32",
    "uint32_t *": "*mut u32",
    "PalTextSize32 *": "*mut PalTextSize32",
    "PalButtonGroupOpaque *": "*mut PalButtonGroupOpaque",
    "PalButtonReaction32 *": "*mut PalButtonReaction32",
    "PalSpriteTransition32 *": "*mut PalSpriteTransition32",
    "const PalSpriteTransition32 *": "*const PalSpriteTransition32",
    "const int32_t *": "*const i32",
    "const PalSoundLoadRange32 *": "*const PalSoundLoadRange32",
}


def generate():
    manifest = json.loads((HERE / "pal32.json").read_text())
    assert manifest["schema_version"] == 1
    assert manifest["target"] == "i686-pc-windows"
    assert manifest["pointer_bytes"] == 4
    functions = list(manifest["functions"])
    for included in manifest.get("includes", []):
        extension = json.loads((HERE / included).read_text())
        assert extension["target"] == manifest["target"]
        assert extension["pointer_bytes"] == manifest["pointer_bytes"]
        functions.extend(extension["functions"])
    assert len({f["name"] for f in functions}) == len(functions)
    evidence_files = {}
    rust = [
        "// Generated by reverse/abi/generate.py; edit reverse/abi/pal32.json.",
        "use super::{AbiContract, NativeBuildEvidence};",
        "",
        '#[cfg(all(target_arch = "x86", target_os = "windows"))]',
        "pub mod win32 {",
        "    use super::super::{PalRect32, PalSpriteOpaque, PalRenderOpaque, PalSoundLoadRange32, PalTaskOpaque, PalAnimationFrame32, PalTextSize32, PalSpriteTransition32, PalButtonGroupOpaque, PalButtonReaction32, PalSpriteInfoKoikake32, PalWaveFormatEx32};",
    ]
    header = [
        "/* Generated by reverse/abi/generate.py; edit pal32.json. */",
        "#ifndef SENA_NATIVE_PAL32_H",
        "#define SENA_NATIVE_PAL32_H",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "#if !defined(_WIN32) || (!defined(_M_IX86) && !defined(__i386__))",
        '#error "This header describes native Win32 x86 PAL, not the portable Sena ABI."',
        "#endif",
        "#define PAL_CDECL __cdecl",
        "typedef struct PalSpriteInfoKoikake32 { uint32_t visible, color; float x, y, z; int32_t offset_x, offset_y; uint32_t texture_width, texture_height, cell_width, cell_height; int32_t center_x, center_y, priority; float scale, rotation_x, rotation_y, rotation_z; uint32_t render_mode; } PalSpriteInfoKoikake32;",
        "#pragma pack(push, 2)",
        "typedef struct PalWaveFormatEx32 { uint16_t format_tag, channels; uint32_t samples_per_second, average_bytes_per_second; uint16_t block_align, bits_per_sample, extra_size; } PalWaveFormatEx32;",
        "#pragma pack(pop)",
        "typedef struct PalSpriteOpaque PalSpriteOpaque;",
        "typedef struct PalRenderOpaque PalRenderOpaque;",
        "typedef struct PalTaskOpaque PalTaskOpaque;",
        "typedef struct PalButtonGroupOpaque PalButtonGroupOpaque;",
        "typedef struct PalButtonReaction32 { uint32_t completed_address, hovered_address, pending_address; } PalButtonReaction32;",
        "typedef struct PalSpriteTransition32 { int32_t transition_type, state; uint32_t render_address, first_sprite_address, second_sprite_address; int32_t last_frame; uint32_t duration_ms, start_time_ms; } PalSpriteTransition32;",
        "typedef struct PalTextSize32 { int32_t cx, cy; } PalTextSize32;",
        "typedef struct PalRect32 { int32_t left, top, right, bottom; } PalRect32;",
        "typedef struct PalRasterSource32 { uint32_t period_ms; float undulate_x, undulate_y; } PalRasterSource32;",
        "typedef struct PalSoundLoadRange32 { uint32_t enabled, initial_start_bytes, loop_start_bytes, loop_end_bytes; } PalSoundLoadRange32;",
        "typedef struct PalAnimationFrame32 { PalRect32 rect; uint32_t duration_ms; int32_t next; } PalAnimationFrame32;",
        '#if defined(__cplusplus)',
        '#define PAL_STATIC_ASSERT static_assert',
        'extern "C" {',
        '#else',
        '#define PAL_STATIC_ASSERT _Static_assert',
        '#endif',
        'PAL_STATIC_ASSERT(sizeof(PalButtonReaction32) == 12, "button reaction size");',
        'PAL_STATIC_ASSERT(offsetof(PalButtonReaction32, pending_address) == 8, "button pending offset");',
        'PAL_STATIC_ASSERT(sizeof(PalSpriteInfoKoikake32) == 76, "Koikake sprite info size");',
        'PAL_STATIC_ASSERT(offsetof(PalSpriteInfoKoikake32, scale) == 56, "Koikake sprite scale offset");',
        'PAL_STATIC_ASSERT(offsetof(PalSpriteInfoKoikake32, render_mode) == 72, "Koikake sprite mode offset");',
        'PAL_STATIC_ASSERT(sizeof(PalWaveFormatEx32) == 18, "sound format size");',
        'PAL_STATIC_ASSERT(offsetof(PalWaveFormatEx32, extra_size) == 16, "sound format extra size offset");',
        'PAL_STATIC_ASSERT(sizeof(void *) == 4, "native pointer width");',
        'PAL_STATIC_ASSERT(sizeof(PalSpriteTransition32) == 32, "transition record size");',
        'PAL_STATIC_ASSERT(offsetof(PalSpriteTransition32, start_time_ms) == 28, "transition start time offset");',
        'PAL_STATIC_ASSERT(sizeof(PalTextSize32) == 8, "text size record");',
        'PAL_STATIC_ASSERT(offsetof(PalTextSize32, cy) == 4, "text size offset");',
        'PAL_STATIC_ASSERT(sizeof(PalRect32) == 16, "native RECT size");',
        'PAL_STATIC_ASSERT(offsetof(PalRect32, bottom) == 12, "native RECT offset");',
        'PAL_STATIC_ASSERT(sizeof(PalRasterSource32) == 12, "raster source size");',
        'PAL_STATIC_ASSERT(offsetof(PalRasterSource32, undulate_y) == 8, "raster source offset");',
        'PAL_STATIC_ASSERT(sizeof(PalSoundLoadRange32) == 16, "sound load range size");',
        'PAL_STATIC_ASSERT(offsetof(PalSoundLoadRange32, loop_end_bytes) == 12, "sound load range offset");',
        'PAL_STATIC_ASSERT(sizeof(PalAnimationFrame32) == 24, "animation frame size");',
        'PAL_STATIC_ASSERT(offsetof(PalAnimationFrame32, duration_ms) == 16, "animation duration offset");',
        'PAL_STATIC_ASSERT(offsetof(PalAnimationFrame32, next) == 20, "animation next offset");',
        "",
    ]
    for function in functions:
        assert function["abi_status"] == "confirmed"
        assert function["calling_convention"] == "cdecl"
        assert function["notes"] and function["implementation"]
        assert function["evidence"]
        for evidence in function["evidence"].values():
            path = ROOT / evidence["file"]
            if path not in evidence_files:
                evidence_files[path] = json.loads(path.read_text())
            recorded = evidence_files[path]
            assert recorded["sha256"] == evidence["binary_sha256"], function["name"]
            assert len(recorded["sha256"]) == 64
            matches = [entry for entry in recorded["functions"]
                       if int(entry["ea"], 0) == int(evidence["address"], 0)]
            assert len(matches) == 1, function["name"]
            assert matches[0]["name"] == function.get("export_name", function["name"]), function["name"]
            assert matches[0]["disassembly"], function["name"]
        params = function["parameters"]
        assert all(p["stack_bytes"] == 4 for p in params)
        ret = RUST_TYPES[function["return_type"]]
        rust_params = ", ".join(f'{p["name"]}: {RUST_TYPES[p["type"]]}' for p in params)
        c_params = ", ".join(f'{p["type"]} {p["name"]}' for p in params) or "void"
        name = function["name"]
        rust += [f'    /// {function["notes"]}', f'    pub type {name} = unsafe extern "C" fn({rust_params}) -> {ret};']
        export_name = function.get("export_name", name)
        header += [f'/* Export: {export_name}. {function["notes"]} */']
        if export_name != name:
            header += [f'typedef {function["return_type"]} (PAL_CDECL *{name})({c_params});']
        else:
            header += [f'{function["return_type"]} PAL_CDECL {name}({c_params});']
    rust += ["}", "", "pub const CONTRACTS: &[AbiContract] = &["]
    for function in functions:
        params = function["parameters"]
        c_params = ", ".join(f'{p["type"]} {p["name"]}' for p in params) or "void"
        prototype = f'{function["return_type"]} __cdecl {function["name"]}({c_params})'
        rust += [
            "    AbiContract {",
            f'        name: {json.dumps(function.get("export_name", function["name"]))},',
            f'        prototype: {json.dumps(prototype)},',
            f'        stack_bytes: {sum(p["stack_bytes"] for p in params)},',
            f'        implementation: {json.dumps(function["implementation"])},',
            f'        notes: {json.dumps(function["notes"])},',
            "        evidence: &[",
        ]
        for build, evidence in function["evidence"].items():
            rust += ["            NativeBuildEvidence {",
                     f'                build: {json.dumps(build)},',
                     f'                address: {evidence["address"]},',
                     f'                binary_sha256: {json.dumps(evidence["binary_sha256"])},',
                     f'                evidence: {json.dumps(evidence["file"])},', "            },"]
        rust += ["        ],", "    },"]
    rust += ["];", ""]
    header += ['#if defined(__cplusplus)', '}', '#endif', '#undef PAL_STATIC_ASSERT', '#undef PAL_CDECL', '#endif', '']
    return {
        ROOT / "crates/pal-vm/src/abi/generated.rs": "\n".join(rust),
        HERE / "pal32.h": "\n".join(header),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, source in generate().items():
        if args.check:
            if not path.is_file() or path.read_text() != source:
                raise SystemExit(f"Stale PAL ABI declarations: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(source)


if __name__ == "__main__":
    main()
